/**
 * vue3-flag-icons ships all 269 flags as percent-encoded SVG data URIs inside one
 * stylesheet. That stylesheet is 5.0 MB and it is render-blocking: the browser will
 * not paint until every flag the customer will never see has been parsed. It is 97%
 * of our CSS payload.
 *
 * This unpacks it. Each data URI becomes a file under src/assets/flags/, and the
 * generated stylesheet references them by URL, so the browser fetches only the four
 * or five flags actually on screen. 5.0 MB of blocking CSS becomes ~25 KB.
 *
 * SD-1180: these live under src/ rather than public/ so that Vite fingerprints
 * them. A file in public/ is copied out verbatim and keeps its name for ever,
 * which meant a corrected flag could not reach anyone still holding the old one -
 * and /flags/** was cached for a week. Writing them here puts each flag at
 * /assets/<name>-<hash>.svg, so fixing a flag changes its URL and the fix lands
 * on the next load instead of in seven days.
 *
 * The reference has to stay relative for that to work: Vite rewrites url() it can
 * resolve on disk, and an absolute /flags/... is left alone as a runtime path.
 *
 * Both outputs are generated, gitignored, and rebuilt by the pre* npm hooks - they
 * are a projection of whatever version of the package is installed, never a
 * hand-edited source file.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(root, 'node_modules', 'vue3-flag-icons', 'dist', 'style.css');
const FLAG_DIR = path.join(root, 'src', 'assets', 'flags');
const OUT_CSS = path.join(root, 'src', 'assets', 'flags.css');

// The package scopes every selector to the data-v attribute of its own component.
// We drop the attribute: the rules still match that component, and dropping it
// means the generated sheet does not break the day the package is rebuilt with a
// different hash.
const unscope = selector => selector.replace(/\[data-v-[0-9a-f]+\]/g, '').trim();

// A file name per flag variant. `.fi-us` is the 4:3 flag, `.fi-us.fis` the square.
function assetName(selector) {
    const wide = selector.match(/^\.fi-([a-z0-9-]+)$/);
    if (wide) return `${wide[1]}.svg`;

    const square = selector.match(/^\.fi-([a-z0-9-]+)\.fis$/);
    if (square) return `${square[1]}-square.svg`;

    return null;
}

const css = fs.readFileSync(SOURCE, 'utf8');
const rules = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)];
if (rules.length === 0) throw new Error(`no rules parsed out of ${SOURCE} - has the package changed shape?`);

fs.rmSync(FLAG_DIR, {recursive: true, force: true});
fs.mkdirSync(FLAG_DIR, {recursive: true});

const out = ['/* Generated by scripts/generate-flag-assets.mjs. Do not edit. */'];
let written = 0;

for (const [, rawSelector, body] of rules) {
    const selector = unscope(rawSelector);
    // The package is not consistent: most flags are percent-encoded and quoted,
    // a handful (Guam) are base64 and unquoted. Miss one and it stays inline,
    // which is exactly how a 300 KB flag survived the first pass of this script.
    //
    // Terminate on the right character, and only the right character. This was
    // one pattern with `([^")]*)` for the payload - "up to the quote or the
    // closing paren" - which is wrong, because an SVG is full of parentheses:
    // `clip-path='url(#lr-a)'`, `transform='translate(...)'`, `rgb(...)`. The
    // capture stopped at the first one and 300 of the 540 variants were written
    // to disk cut in half. Nothing failed. The stylesheet was valid, the file
    // existed, it served 200, and it painted nothing - India, the United
    // States, Kenya, Rwanda and 140 others were blank on every tenant until
    // somebody looked at a screen.
    //
    // A quoted URI can only be ended by its quote. An unquoted one ends at the
    // paren, which is safe because the only unquoted case is base64, and base64
    // has no parentheses.
    const uri =
        body.match(/background-image:\s*url\(\s*"data:image\/svg\+xml(;base64)?,([^"]*)"\s*\)/) ??
        body.match(/background-image:\s*url\(\s*data:image\/svg\+xml(;base64)?,([^)]*?)\s*\)/);
    const name = assetName(selector);

    if (!uri || !name) {
        // Structural rules (.fi sizing, .round) and anything we do not recognise
        // are carried through untouched rather than dropped on the floor.
        out.push(`${selector}{${body.trim()}}`);
        continue;
    }

    const svg = uri[1] ? Buffer.from(uri[2], 'base64').toString('utf8') : decodeURIComponent(uri[2]);

    // Never write a partial flag. The whole failure above was silent because a
    // truncated file is still a file: it has a name, it has bytes, it returns
    // 200, and the only place it shows up is a customer's screen. Refusing to
    // write one turns that into a failed build.
    if (! svg.trimEnd().endsWith('</svg>')) {
        throw new Error(
            `${name} decoded to ${svg.length} bytes that do not end in </svg> - the payload was ` +
            `truncated, so the extraction pattern no longer matches how the package encodes flags. ` +
            `Ends: ${JSON.stringify(svg.slice(-60))}`,
        );
    }

    fs.writeFileSync(path.join(FLAG_DIR, name), svg);
    out.push(`${selector}{background-image:url("./flags/${name}")}`);
    written++;
}

const generated = out.join('\n') + '\n';
// Nothing may stay inline. Without this the script fails open: an encoding it does
// not recognise is silently carried through and the payload never shrinks.
if (generated.includes('data:image')) {
    const stuck = [...generated.matchAll(/(\.fi-[a-z0-9.-]+)\{background-image:url\(\s*"?data:/g)].map(m => m[1]);
    throw new Error(`these flags are still inline, in an encoding this script does not read: ${stuck.join(', ')}`);
}

fs.writeFileSync(OUT_CSS, generated);

const sourceKb = (Buffer.byteLength(css) / 1024).toFixed(0);
const outKb = (Buffer.byteLength(generated) / 1024).toFixed(0);
console.log(`flags: ${written} files written to src/assets/flags/`);
console.log(`flags: blocking CSS ${sourceKb} KB -> ${outKb} KB`);
